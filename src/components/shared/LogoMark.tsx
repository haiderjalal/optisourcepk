export function LogoMark({
  className,
  tone = "colour",
}: {
  className?: string;
  /** `colour` on light grounds, `inverted` on navy, `mono` inherits currentColor. */
  tone?: "colour" | "inverted" | "mono";
}) {
  const primary =
    tone === "colour"
      ? "#0f2741"
      : tone === "inverted"
        ? "#ffffff"
        : "currentColor";
  const secondary =
    tone === "mono"
      ? "currentColor"
      : tone === "inverted"
        ? "#cdd4de"
        : "#c2cbd4";

  return (
    <svg
      viewBox={MARK_VIEWBOX}
      className={cn("shrink-0", className)}
      role="img"
      aria-label="OptiSource PK"
      fill="none"
    >
      <path
        d={BLADE_SECONDARY}
        fill={secondary}
        opacity={tone === "mono" ? 0.45 : 1}
      />
      <path d={BLADE_PRIMARY} fill={primary} />
    </svg>
  );
}
